def build_dataset(output_path: str = "data/processed/players.json") -> list:
    """
    Processes RAW_PLAYERS into the final clean dataset.
    Adds computed fields and validates each entry.
    """
    print("\n" + "="*60)
    print("DATASET BUILDER — Starting")
    print("="*60)

    final_players = []

    for p in RAW_PLAYERS:
        # Add computed fields
        player = dict(p)
        player["id"] = slugify(p["name"])
        player["total_seasons"] = len(p["seasons_played"])
        player["veteran"] = p["first_season"] <= 2012   # Played from early IPL
        player["played_for_multiple_teams"] = len(set(p["ipl_teams"])) > 1
        player["is_captain_ever"] = len(p["captained_teams"]) > 0
        player["won_title"] = p["titles_won"] > 0
        player["cap_winner"] = p["orange_cap"] or p["purple_cap"]

        final_players.append(player)

    # Sort by high_profile first, then name
    final_players.sort(key=lambda x: (not x["high_profile"], x["name"]))

    save_json(final_players, output_path)

    # Print summary stats
    print(f"\n{'='*60}")
    print(f"✅ Total players: {len(final_players)}")
    print(f"   Indian players: {sum(1 for p in final_players if not p['overseas'])}")
    print(f"   Overseas players: {sum(1 for p in final_players if p['overseas'])}")
    print(f"   Active players: {sum(1 for p in final_players if p['active'])}")
    print(f"   High profile: {sum(1 for p in final_players if p['high_profile'])}")
    print(f"   Cap winners: {sum(1 for p in final_players if p['cap_winner'])}")
    roles = {}
    for p in final_players:
        roles[p['primary_role']] = roles.get(p['primary_role'], 0) + 1
    print(f"   Roles: {roles}")

    return final_players


