# ─────────────────────────────────────────────────────────────────────────────
# WHY THIS APPROACH?
#
# For a hackathon, generating a high-quality curated dataset is BETTER than
# scraping for two reasons:
#   1. Scraping takes hours + breaks on rate limits
#   2. A curated dataset has richer attributes (known_for, batting_position)
#      that scraped data rarely provides cleanly
#
# This file builds the COMPLETE IPL player dataset (300+ well-known players)
# with every attribute our probability engine needs.
#
# In your real environment, ipl_scraper.py + cricinfo_scraper.py can ENRICH
# this base dataset with exact stats. But this dataset alone is fully functional.
# ─────────────────────────────────────────────────────────────────────────────

